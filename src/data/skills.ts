export const skills: Skill[] = [...nour];

export function skillsFor(employeeId: string) {
  return skills.filter((s) => s.employeeId === employeeId);
}

export function featuredSkillsFor(employeeId: string) {
  const list = skillsFor(employeeId);
  const featured = list.filter((s) => s.featured);
  return featured.length > 0 ? featured : list.slice(0, 4);
}

export function skillsByCategory(employeeId: string) {
  const groups = new Map<SkillCategory, Skill[]>();
  for (const s of skillsFor(employeeId)) {
    const arr = groups.get(s.category) ?? [];
    arr.push(s);
    groups.set(s.category, arr);
  }
  return [...groups.entries()];
}

export function getSkill(id: string) {
  return skills.find((s) => s.id === id);
}
